defmodule KogenCredo.CoreSupport.Scope do
  @moduledoc """
  Lexical walk over an AST that tracks `alias`, `import` and the enclosing module.

  `walk/3` calls `fun.(node, env, acc)` for every node, pre-order, with the `env`
  that is in force at that node:

    * `env.aliases`: short name => module *name* (`"MyApp.Repo"`, see
      `t:KogenCredo.CoreSupport.Ast.module_name/0`), plus `:__MODULE__` => the enclosing
      module's name when it is known (use `KogenCredo.CoreSupport.Aliases.resolve/2`);
    * `env.imports`: `[{module_name, only}]` where `only` is `:all`, a list of
      `{name, arity}`, or `{:except, [{name, arity}]}`;
    * `env.locals`: `{name, arity}` of the functions the enclosing module defines itself
      (nested modules excluded), so a local definition can shadow an import.

  Scoping follows Elixir: a declaration is visible to the *following* expressions of
  the same block and below, and never leaks out of the block, function or module that
  contains it. A nested `defmodule Inner` is `Outer.Inner` and aliases `Inner`.
  This is still syntactic: `use`-injected aliases/imports and `alias` generated by
  macros are invisible.
  """

  alias KogenCredo.CoreSupport.Aliases
  alias KogenCredo.CoreSupport.Ast

  @type env :: %{
          aliases: %{optional(atom()) => Ast.module_name()},
          imports: [
            {Ast.module_name(), :all | [{atom(), arity()}] | {:except, [{atom(), arity()}]}}
          ],
          locals: MapSet.t()
        }

  @doc "Empty environment."
  @spec new_env() :: env()
  def new_env, do: %{aliases: %{}, imports: [], locals: MapSet.new()}

  @doc "Pre-order accumulate with the lexical environment in force at each node."
  @spec walk(Macro.t(), acc, (Macro.t(), env(), acc -> acc)) :: acc when acc: term()
  def walk(ast, acc, fun) do
    env = %{new_env() | locals: locals_of(ast)}
    {_, acc} = visit(ast, env, acc, fun)
    acc
  end

  # Functions defined directly in this scope (nested modules excluded).
  defp locals_of(ast) do
    ast
    |> Ast.strip_modules()
    |> Aliases.local_functions()
  end

  defp visit({:__block__, _, exprs} = node, env, acc, fun) when is_list(exprs) do
    entered = fun.(node, env, acc)

    {_, visited} =
      Enum.reduce(exprs, {env, entered}, fn expr, {env, acc} -> visit(expr, env, acc, fun) end)

    {env, visited}
  end

  defp visit({:alias, _, args} = node, env, acc, fun) when is_list(args) do
    entered = fun.(node, env, acc)
    {_, visited} = visit_children(args, env, entered, fun)
    {bind_alias(args, env), visited}
  end

  defp visit({:import, _, [mod | rest]} = node, env, acc, fun) do
    entered = fun.(node, env, acc)
    {_, visited} = visit_children([mod | rest], env, entered, fun)

    imported_env =
      case Aliases.resolve(mod, env.aliases) do
        nil -> env
        module -> %{env | imports: [{module, import_only(rest)} | env.imports]}
      end

    {imported_env, visited}
  end

  defp visit({:require, _, [mod, opts]} = node, env, acc, fun) when is_list(opts) do
    entered = fun.(node, env, acc)
    {_, visited} = visit_children([mod, opts], env, entered, fun)

    {bind_require(mod, opts, env), visited}
  end

  defp visit({:defmodule, _, [name | rest]} = node, env, acc, fun) do
    entered = fun.(node, env, acc)
    {_, named} = visit(name, env, entered, fun)
    {inner, outer} = module_envs(name, env)

    {_, visited} =
      Enum.reduce(rest, {inner, named}, fn
        [do: body], {inner, acc} ->
          visit(body, %{inner | locals: locals_of(body)}, acc, fun)

        other, {inner, acc} ->
          visit_children([other], inner, acc, fun)
      end)

    {outer, visited}
  end

  defp visit({form, _, args} = node, env, acc, fun) when is_list(args) do
    entered = fun.(node, env, acc)
    {_, with_form} = visit(form, env, entered, fun)
    visit_children(args, env, with_form, fun)
  end

  defp visit({left, right} = node, env, acc, fun) do
    entered = fun.(node, env, acc)
    {_, with_left} = visit(left, env, entered, fun)
    {_, with_right} = visit(right, env, with_left, fun)
    {env, with_right}
  end

  defp visit(list, env, acc, fun) when is_list(list), do: visit_children(list, env, acc, fun)

  defp visit(other, env, acc, fun), do: {env, fun.(other, env, acc)}

  defp visit_children(children, env, acc, fun) do
    {_, visited} =
      Enum.reduce(children, {env, acc}, fn child, {env, acc} ->
        {_, child_acc} = visit(child, env, acc, fun)
        {env, child_acc}
      end)

    {env, visited}
  end

  # --- alias / module bookkeeping ---

  defp bind_require(mod, opts, env) do
    with {:__aliases__, _, [short]} <- opts[:as],
         module when module != nil <- Aliases.resolve(mod, env.aliases) do
      put_in(env.aliases[short], module)
    else
      _ -> env
    end
  end

  defp bind_alias([{:__aliases__, _, _} = mod], env), do: bind_short(mod, nil, env)

  defp bind_alias([{:__aliases__, _, _} = mod, opts], env) when is_list(opts) do
    case opts[:as] do
      {:__aliases__, _, [short]} -> bind_short(mod, short, env)
      _ -> bind_short(mod, nil, env)
    end
  end

  defp bind_alias([{{:., _, [{:__aliases__, _, _} = base, :{}]}, _, children}], env)
       when is_list(children) do
    case Aliases.resolve(base, env.aliases) do
      nil ->
        env

      base_mod ->
        Enum.reduce(children, env, &bind_child(&1, base_mod, &2))
    end
  end

  defp bind_alias([{{:., _, [{:__MODULE__, _, _}, :{}]}, _, children}], env)
       when is_list(children) do
    case env.aliases do
      %{__MODULE__: current} ->
        Enum.reduce(children, env, &bind_child(&1, current, &2))

      _ ->
        env
    end
  end

  defp bind_alias(_, env), do: env

  # One member of `alias Base.{A, B.C}`: bound under its last segment to `Base.A` / `Base.B.C`.
  defp bind_child({:__aliases__, _, [_ | _] = rest}, base_mod, env) do
    if Enum.all?(rest, &is_atom/1),
      do: put_in(env.aliases[List.last(rest)], Ast.join_name([base_mod | rest])),
      else: env
  end

  defp bind_child(_, _, env), do: env

  defp bind_short({:__aliases__, _, parts} = node, short, env) do
    case Aliases.resolve(node, env.aliases) do
      nil ->
        env

      module ->
        last = short || last_atom(parts)
        if is_atom(last), do: put_in(env.aliases[last], module), else: env
    end
  end

  defp last_atom(parts) do
    case List.last(parts) do
      atom when is_atom(atom) -> atom
      _ -> nil
    end
  end

  # `{env inside the module body, env after the defmodule}`.
  defp module_envs({:__aliases__, _, [first | rest] = parts} = name, env) do
    if resolvable_name?(first, rest),
      do: nested_envs(name, first, parts, env),
      else: {env, env}
  end

  defp module_envs(_, env), do: {env, env}

  defp resolvable_name?(first, rest) do
    (is_atom(first) or match?({:__MODULE__, _, _}, first)) and Enum.all?(rest, &is_atom/1)
  end

  defp nested_envs(name, first, parts, env) do
    nested? = Map.has_key?(env.aliases, :__MODULE__) and is_atom(first)

    full =
      if nested?,
        do: Ast.join_name([env.aliases.__MODULE__ | parts]),
        else: Aliases.resolve(name, env.aliases)

    inner = if full, do: put_in(env.aliases[:__MODULE__], full), else: env

    outer =
      if nested?,
        do: put_in(env.aliases[first], Ast.join_name([env.aliases.__MODULE__, first])),
        else: env

    {inner, outer}
  end

  defp import_only([opts]) when is_list(opts), do: import_kind(opts[:only], opts[:except])

  defp import_only(_), do: :all

  defp import_kind(only, _) when is_list(only), do: function_pairs(only)
  defp import_kind(_, except) when is_list(except), do: {:except, function_pairs(except)}
  defp import_kind(_, _), do: :all

  defp function_pairs(list), do: for({f, a} <- list, is_atom(f), is_integer(a), do: {f, a})
end
